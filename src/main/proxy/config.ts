// The core's runtime configuration as a pure function. The gate lives here as well: a closed
// config has no route out except the egress probe, so "closed" holds even for pages already open.
import { stringify } from 'yaml';

export const GROUP = 'PROXY';

export interface Ports {
  /** the only proxy the browser knows */
  browser: number;
  /** used by the egress check alone; always routed through the selected node */
  probe: number;
  controller: number;
}

export interface RuntimeInput {
  ports: Ports;
  secret: string;
  open: boolean;
  proxies: Record<string, unknown>[];
  /** the user's node; it leads the group, so every (re)load starts on it */
  selected: string;
  allowPrivateNetwork: boolean;
  /** OS-resolved uplink for the core's upstream sockets, not browser traffic (independent mode). */
  outboundInterface?: string;
}

const LOOPBACK_AND_LINK_LOCAL = ['IP-CIDR,0.0.0.0/8', 'IP-CIDR,127.0.0.0/8', 'IP-CIDR,169.254.0.0/16', 'IP-CIDR6,::1/128', 'IP-CIDR6,fe80::/10'];
const PRIVATE = ['IP-CIDR,10.0.0.0/8', 'IP-CIDR,100.64.0.0/10', 'IP-CIDR,172.16.0.0/12', 'IP-CIDR,192.168.0.0/16', 'IP-CIDR6,fc00::/7'];

export function buildRuntimeConfig(i: RuntimeInput): Record<string, unknown> {
  const names = i.proxies.map((p) => String(p.name));
  // A select group starts on its first member: the chosen node goes first, so a reload never
  // routes through another one, not even for a moment.
  const members = names.includes(i.selected) ? [i.selected, ...names.filter((n) => n !== i.selected)] : names;
  const reject = [
    'DOMAIN,localhost,REJECT',
    ...[...LOOPBACK_AND_LINK_LOCAL, ...(i.allowPrivateNetwork ? [] : PRIVATE)].map((r) => `${r},REJECT,no-resolve`),
  ];
  const socks = (name: string, port: number) => ({ name, type: 'socks', listen: '127.0.0.1', port, udp: false });
  return {
    'bind-address': '127.0.0.1',
    ...(i.outboundInterface ? { 'interface-name': i.outboundInterface } : {}),
    'allow-lan': false,
    ipv6: false,
    mode: 'rule',
    'find-process-mode': 'off',
    'log-level': 'warning',
    'geo-auto-update': false,
    'external-controller': `127.0.0.1:${i.ports.controller}`,
    secret: i.secret,
    profile: { 'store-selected': false, 'store-fake-ip': false },
    tun: { enable: false },
    dns: {
      enable: true,
      ipv6: false,
      'enhanced-mode': 'normal',
      'use-hosts': false,
      'use-system-hosts': false,
      'prefer-h3': false,
      'respect-rules': true,
      'default-nameserver': ['1.1.1.1'],
      'proxy-server-nameserver': ['https://1.1.1.1/dns-query'],
      nameserver: [`https://1.1.1.1/dns-query#${GROUP}`],
    },
    listeners: [socks('browser', i.ports.browser), socks('probe', i.ports.probe)],
    proxies: i.proxies,
    // With no subscription yet the group still exists and can only reject.
    'proxy-groups': [{ name: GROUP, type: 'select', proxies: members.length ? members : ['REJECT'], 'empty-fallback': 'REJECT' }],
    rules: [
      `IN-NAME,probe,${GROUP}`,
      ...(i.open ? [...reject, `MATCH,${GROUP}`] : ['MATCH,REJECT']),
    ],
  };
}

export function renderRuntimeConfig(i: RuntimeInput): string {
  return `# 由 Cave 每次启动时生成，请勿手改 / generated by Cave, do not edit\n${stringify(buildRuntimeConfig(i), { lineWidth: 0 })}`;
}
