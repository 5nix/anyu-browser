import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { startWorld } from './harness.mjs';
import { devtoolsPort, evaluate, waitFor, screenshot, gateState } from './cdp.mjs';

test('cached favicons, menu icons and Windows chrome', async t => {
  process.env.CAVE_TEST_WINDOWS_CHROME = '1';
  const w = await startWorld({ blank: true, tls: true, extra: ['--remote-debugging-port=0'] });
  delete process.env.CAVE_TEST_WINDOWS_CHROME;
  t.after(() => w.stop());
  const port = await devtoolsPort(w.log), shellTarget = u => u.endsWith('/shell.html'), overlayTarget = u => u.endsWith('/overlay.html');
  const shell = expr => evaluate(port, shellTarget, expr), overlay = expr => evaluate(port, overlayTarget, expr);
  const dir = process.env.CAVE_BATCH5_SCREENSHOTS;
  if (dir) await mkdir(dir, { recursive: true });
  const shot = async (name, target) => { if (dir) await writeFile(join(dir, name + '.png'), await screenshot(port, target)); };
  await waitFor(() => shell("document.body.classList.contains('win')"));
  await shell("cave.setTabLayout('side')");
  await waitFor(() => shell("document.body.classList.contains('side')"));
  await shot('windows-side-light', shellTarget);
  await shell("cave.setTheme('dark')"); await waitFor(() => shell("document.documentElement.dataset.theme === 'dark' || getComputedStyle(document.body).backgroundColor === 'rgb(18, 18, 19)'"));
  await shot('windows-side-dark', shellTarget);
  await shell("cave.setTabLayout('top')"); await waitFor(() => shell("document.body.classList.contains('top')"));
  await shot('windows-top-dark', shellTarget);
  await shell("cave.setTheme('light')");
  await waitFor(async () => (await gateState(port)) === 'open', 60000);
  const url = 'http://fp.cave.test/favicon-page';
  await shell(`cave.navigate(${JSON.stringify(url)})`);
  await waitFor(() => shell("!!document.querySelector('.tab.active .fav img')"));
  const requests = w.fixture.requests.filter(x => x.host === 'icon.cave.test').length;
  await shell(`cave.bookmarkAdd(null, 'link', 'Favicon fixture', ${JSON.stringify(url)})`);
  await shell(`cave.saveShortcut({ name: 'Favicon fixture', url: ${JSON.stringify(url)} })`);
  await shell("cave.getState().then(s => cave.openTabMenu(s.active, {x: 100, y: 30, width: 1, height: 1}))");
  await waitFor(() => overlay("document.querySelectorAll('[role=menuitem]').length > 0"));
  assert.equal(await overlay("[...document.querySelectorAll('[role=menuitem]')].every(e => !!e.querySelector('svg'))"), true);
  await new Promise(r => setTimeout(r, 250)); await shot('tab-context-menu', overlayTarget);
  await shell('cave.closeSurface()');
  await shell("cave.run('history.open')");
  const history = u => u.endsWith('/history.html'); await waitFor(() => evaluate(port, history, "!!document.querySelector('.row-favicon')")); await shot('history-favicons', history);
  await shell("cave.run('bookmarks.open')");
  const bookmarks = u => u.endsWith('/bookmarks.html'); await waitFor(() => evaluate(port, bookmarks, "!!document.querySelector('.row-favicon')")); await shot('bookmarks-favicons', bookmarks);
  await shell('cave.newTab()');
  const home = u => u.endsWith('/home.html'); await waitFor(() => evaluate(port, home, "!!document.querySelector('.avatar img')")); await shot('home-favicons', home);
  await shell("cave.run('address.focus')");
  await waitFor(() => shell("cave.getState().then(s => !!s.address)"));
  await shell("document.querySelector('#address').value = 'fp.cave'; document.querySelector('#address').dispatchEvent(new Event('input', {bubbles:true}))");
  await waitFor(() => overlay("!!document.querySelector('#suggestions img')")); await shot('suggestions-favicons', overlayTarget);
  assert.equal(w.fixture.requests.filter(x => x.host === 'icon.cave.test').length, requests);
  await shell("document.querySelector('#address').dispatchEvent(new KeyboardEvent('keydown', {key:'Escape', bubbles:true}))");
  await waitFor(() => shell('cave.getState().then(s => !s.address)'));
  await shell(`cave.navigate(${JSON.stringify(w.httpsUrl)})`);
  await waitFor(async () => { const s = await shell('cave.getState()'); return s.tabs.find(t => t.id === s.active)?.url === w.httpsUrl && !s.tabs.find(t => t.id === s.active)?.loading; });
  await shell("document.querySelector('#site-icon').click()");
  await waitFor(() => overlay("!!document.querySelector('.site-info-certificate')"));
  await overlay("document.querySelector('.site-info-certificate').open = true");
  await new Promise(r => setTimeout(r, 400)); await shot('certificate-details', overlayTarget);
});
